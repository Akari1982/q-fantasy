MATRIX* PsyqRotMatrix(SVECTOR* r, MATRIX* m)
{
    int var1, var2, var3, var4, var5, var6, var7, var8;

    var6 = rcossin_tbl[(r->vx & 0xfff) * 2];
    var3 = rcossin_tbl[(r->vx & 0xfff) * 2 + 1];
    var7 = rcossin_tbl[(r->vy & 0xfff) * 2];
    var4 = rcossin_tbl[(r->vy & 0xfff) * 2 + 1];
    var8 = rcossin_tbl[(r->vz & 0xfff) * 2];
    var5 = rcossin_tbl[(r->vz & 0xfff) * 2 + 1];
    var1 = -(int)var7;
    var2 = var5 * var1 >> 0xc;
    var1 = var8 * var1 >> 0xc;

    m->m[0][0] = (short)(var5 * var4 >> 0xc);
    m->m[0][1] = (short)(-(var8 * var4) >> 0xc);
    m->m[0][2] = (short)var7;
    m->m[1][0] = (short)(var8 * var3 >> 0xc) - (short)(var2 * var6 >> 0xc);
    m->m[1][1] = (short)(var5 * var3 >> 0xc) + (short)(var1 * var6 >> 0xc);
    m->m[1][2] = (short)(-(var4 * var6) >> 0xc);
    m->m[2][0] = (short)(var2 * var3 >> 0xc) + (short)(var8 * var6 >> 0xc);
    m->m[2][1] = (short)(var5 * var6 >> 0xc) - (short)(var1 * var3 >> 0xc);
    m->m[2][2] = (short)(var4 * var3 >> 0xc);

    return m;
}



MATRIX* PsyqScaleMatrix(MATRIX* m, VECTOR* v)
{
    m->m[0][0] = m->m[0][0] * v->vx >> 0xc;
    m->m[0][1] = m->m[0][1] * v->vx >> 0xc;
    m->m[0][2] = m->m[0][2] * v->vx >> 0xc;
    m->m[1][0] = m->m[1][0] * v->vy >> 0xc;
    m->m[1][1] = m->m[1][1] * v->vy >> 0xc;
    m->m[1][2] = m->m[1][2] * v->vy >> 0xc;
    m->m[2][0] = m->m[2][0] * v->vz >> 0xc;
    m->m[2][1] = m->m[2][1] * v->vz >> 0xc;
    m->m[2][2] = m->m[2][2] * v->vz >> 0xc;

    return m;
}



